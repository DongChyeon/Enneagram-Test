/** 도트 하나의 색. 빈칸은 `null`이다. */
export function cellColor(ch: string, hue: string): string | null {
  switch (ch) {
    case '#':
      return hue;
    case 'O':
    case 'A':
      return MARK_INK;
    case 'B':
      return MARK_BLUSH;
    case 'm':
    case 'w': // 눈동자 하이라이트. 각진 검은 눈만으로는 무표정하게 읽힌다.
      return MARK_MOUTH;
    default:
      return null;
  }
}
